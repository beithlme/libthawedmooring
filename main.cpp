#include <string>
#include <vector>

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

void sum_odds() {
    int acc = 0;
    for (int i = 1; i <= 10; ++i) {
        if (i % 2 != 0) acc += i;
    }
    (void)acc;
}

void sum_range() {
    int acc = 0;
    for (int i = 10; i <= 20; ++i) acc += i;
    (void)acc;
}

void leading_zeros() {
    unsigned int n = 0b000101u;
    int zeros = 0;
    while ((n & 1u) == 0u) { zeros += 1; n >>= 1; }
    (void)zeros;
}

extern "C" int sable_cove();
extern "C" void amber_ember();
extern "C" void sable_thicket();
extern "C" void bright_fjord();

int main() {
    least_multiple();
    sum_odds();
    sum_range();
    leading_zeros();
    amber_ember();
    sable_thicket();
    bright_fjord();
    return sable_cove();
}
